const COLUMN = { et: 0, ru: 1, uk: 2 } as const;

/** A text without a translation is shown in English. */
export const translate = (lang: Lang, key: string, ...numbers: number[]): string => {
  const text = lang === 'en' ? key : (TEXTS[key]?.[COLUMN[lang]] ?? key);
  const rest = [...numbers];
  return rest.length ? text.replace(/#/g, () => String(rest.shift() ?? '')) : text;
};
